class SAVScenarioASL(SAVScenario):
    """
    Scenario for the Attacker Selected Location attack model.

    The attacker knows the topology, the IXPs (IXP_ASNS) and the reflector, and
    attacks from a customer of an IXP close to the reflector v. Candidate IXPs:
        (1) an IXP in v's provider cone (a shared provider of attacker and v)
        (2) an IXP that peers with an AS in v's provider cone, whose peer
            does not adopt SAV
        (3) the remaining IXPs that peer with an AS in v's provider cone
    The attacker tries them in that order until an attempt is not filtered.
    Every candidate is attempted at once here, from one existing customer of
    each; the attack counts as detected at v only if every attempt is detected
    (Metric), which is the outcome of trying them one after another. If no IXP
    is in such a location, a single random IXP is used instead.

    Every attempted IXP never adopts SAV and is not counted in percent
    adoption. One reflector per trial, since the locations are relative to it.
    The topology is not modified.
    """

    def __init__(
        self,
        *,
        scenario_config: SAVScenarioConfig,
        percent_adoption: float | SpecialPercentAdoptions = 0,
        engine: BaseSimulationEngine | None = None,
        attacker_asns: frozenset[int] | None = None,
        victim_asns: frozenset[int] | None = None,
        adopting_asns: frozenset[int] | None = None,
        reflector_asns: frozenset[int] | None = None,
    ):
        assert scenario_config.ScenarioCls == self.__class__, (
            "The config's scenario class is "
            f"{scenario_config.ScenarioCls.__name__}, but the scenario used is "
            f"{self.__class__.__name__}"
        )
        assert scenario_config.num_reflectors == 1, (
            "SAVScenarioASL places the attackers relative to one reflector, "
            f"so num_reflectors must be 1, not {scenario_config.num_reflectors}"
        )
        assert engine, "SAVScenarioASL needs the engine to place the attackers"

        self.scenario_config: SAVScenarioConfig = scenario_config
        self.percent_adoption: float | SpecialPercentAdoptions = percent_adoption

        # The attackers depend on the reflector, so unlike SAVScenario the order
        # is victim -> reflector -> attackers. No attacker is chosen yet, so
        # every draw below is seeded by the victim alone, which bgpy holds fixed
        # for the trial: every scenario of the trial gets the same reflector,
        # candidate IXPs and attackers. The attacker_asns bgpy hands over from
        # the previous scenario are therefore not needed.
        self.attacker_asns: frozenset[int] = frozenset()
        self.victim_asns: frozenset[int] = self._get_victim_asns(
            scenario_config.override_victim_asns, victim_asns, engine
        )
        self.reflector_asns: frozenset[int] = self._get_reflector_asns(
            scenario_config.override_reflector_asns, reflector_asns, engine
        )
        # attempted IXP ASN -> the existing customer attacking through it
        self.ixp_attackers: dict[int, int] = self._get_ixp_attackers(engine)
        self.attacker_asns = (
            frozenset(scenario_config.override_attacker_asns)
            if scenario_config.override_attacker_asns is not None
            else frozenset(self.ixp_attackers.values())
        )

        # From here on, the same as SAVScenario
        self.adopting_asns: frozenset[int] = self._get_sav_adopting_asns(
            adopting_asns, engine
        )
        self.sav_policy_asn_dict = self._build_sav_policy_asn_dict()
        self._ctrl_plane_adopters: frozenset[int] = self._get_ctrl_plane_adopters(engine)

        if scenario_config.override_announcements is not None:
            self.announcements: tuple["Ann", ...] = scenario_config.override_announcements
            self.roas: tuple[ROA, ...] = scenario_config.override_roas or ()
        else:
            self.announcements = self._get_announcements(engine=engine)
            self.roas = self._get_roas(announcements=self.announcements, engine=engine)

        self._reset_and_add_roas_to_roa_checker()

        self.ordered_prefix_subprefix_dict: dict[str, list[str]] = (
            self._get_ordered_prefix_subprefix_dict()
        )

    #############
    # Locations #
    #############

    def _get_ixp_attackers(self, engine: BaseSimulationEngine) -> dict[int, int]:
        """
        Every candidate IXP (see class docstring) mapped to one of its
        existing customers, or a single random IXP if there is no candidate
        """
        (reflector_asn,) = self.reflector_asns
        cone = self._get_provider_cone(engine.as_graph.as_dict[reflector_asn])
        excluded = IXP_ASNS | self.victim_asns | self.reflector_asns

        def customers(ixp_as) -> frozenset[int]:
            return frozenset(ixp_as.customer_asns) - excluded

        # IXPs present in this graph that have a customer to attack from
        ixps = {
            asn: ixp_as
            for asn in IXP_ASNS
            if (ixp_as := engine.as_graph.as_dict.get(asn)) is not None
            and customers(ixp_as)
        }
        candidates = sorted(
            asn for asn, ixp_as in ixps.items()
            if asn in cone or not cone.isdisjoint(ixp_as.peer_asns)
        )
        if not candidates:
            assert ixps, "No IXP AS has a customer in this AS graph"
            candidates = self._sample_asns(frozenset(ixps), 1, "asl_fallback_ixp")

        return {
            ixp: self._sample_asns(customers(ixps[ixp]), 1, f"asl_attacker:{ixp}")[0]
            for ixp in candidates
        }

    @property
    def attempted_ixps(self) -> frozenset[int]:
        return frozenset(getattr(self, "ixp_attackers", ()))

    @staticmethod
    def _get_provider_cone(as_obj: "AS") -> frozenset[int]:
        """Every AS reachable by following providers up from as_obj"""

        cone: set[int] = set()
        stack = list(as_obj.providers)
        while stack:
            current = stack.pop()
            if current.asn not in cone:
                cone.add(current.asn)
                stack.extend(current.providers)
        return frozenset(cone)

    ##############
    # Reflectors #
    ##############

    def _get_possible_reflector_asns(
        self,
        engine: BaseSimulationEngine,
        percent_adoption: float | SpecialPercentAdoptions,
    ) -> frozenset[int]:
        """Same as SAVScenario, minus IXP ASes (reflectors adopt SAV, attempted IXPs never do)"""

        possible = super()._get_possible_reflector_asns(engine, percent_adoption)
        return possible.difference(IXP_ASNS)

    ################
    # SAV adopters #
    ################

    def _get_sav_adopting_asns(
        self,
        adopting_asns: frozenset[int] | None,
        engine: BaseSimulationEngine | None,
    ) -> frozenset[int]:
        """
        Same as SAVScenario, minus the attempted IXPs

        _preset_sav_asns already keeps them out of the random draw. This also
        strips them from adopters that are handed in (override_sav_asns).
        """
        adopters = super()._get_sav_adopting_asns(adopting_asns, engine)
        return adopters.difference(self.attempted_ixps)

    @property
    def _preset_sav_asns(self) -> frozenset[int]:
        """The attempted IXPs are left out of the SAV adopter pool"""

        return super()._preset_sav_asns | self.attempted_ixps
